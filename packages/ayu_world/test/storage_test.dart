import 'dart:io';
import 'dart:typed_data';

import 'package:ayu_world/ayu_world.dart';
import 'package:ayu_world/src/crc32.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  const key = ChunkKey(worldId: ChunkKey.overworld, x: 1, z: 2);
  const other = ChunkKey(worldId: ChunkKey.overworld, x: 3, z: 4);

  test('region log reload, torn tail, and quarantine', () async {
    final root = await Directory.systemTemp.createTemp('ayu-ayur-');
    addTearDown(() async {
      if (await root.exists()) await root.delete(recursive: true);
    });
    final first = RegionLogStorage(root);
    await first.open();
    final payload = const FlatStonePadGenerator().generate(seed: 0, x: 1, z: 2);
    await first.store(
      key,
      payload,
      generatorId: FlatStonePadGenerator.idName,
      generatorVersion: 1,
      regenerable: true,
      playerModified: false,
      finalized: true,
    );
    await first.store(
      other,
      payload,
      generatorId: FlatStonePadGenerator.idName,
      generatorVersion: 1,
      regenerable: true,
      playerModified: false,
      finalized: true,
    );
    await first.flush();
    await first.close();

    final log = File('${root.path}${Platform.pathSeparator}region${Platform.pathSeparator}r.0.0.1.ayur');
    expect(await log.exists(), isTrue);
    final bytes = await log.readAsBytes();
    await log.writeAsBytes(bytes.sublist(0, bytes.length - 3), flush: true);

    final second = RegionLogStorage(root);
    await second.open();
    addTearDown(second.close);
    final hit = await second.lookup(key);
    expect(hit.kind, ChunkLookupKind.hit);
    expect(hit.payload?.primaryBitmask, 1);
    final missed = await second.lookup(other);
    expect(missed.kind, ChunkLookupKind.miss);

    await second.quarantine(key, [1, 2, 3]);
    final quarantined = File(
      '${root.path}${Platform.pathSeparator}quarantine${Platform.pathSeparator}c.1.2.bin',
    );
    expect(await quarantined.exists(), isTrue);
  });

  test('player-modified corruption is not regenerated by lookup', () async {
    final storage = MemoryChunkStorage();
    await storage.quarantine(key, [9, 9, 9]);
    expect(storage.quarantined[key], [9, 9, 9]);
  });

  test('repeated writes keep the last payload and a torn rewrite keeps the previous one', () async {
    final root = await Directory.systemTemp.createTemp('ayu-ayur-rewrite-');
    addTearDown(() async {
      if (await root.exists()) await root.delete(recursive: true);
    });
    final first = RegionLogStorage(root);
    await first.open();
    final older = _varied(key.x, key.z, salt: 1);
    final newer = _varied(key.x, key.z, salt: 2);
    expect(newer.pack(), isNot(orderedEquals(older.pack())));
    await first.store(
      key,
      older,
      generatorId: 'varied',
      generatorVersion: 1,
      regenerable: true,
      playerModified: false,
      finalized: true,
    );
    await first.store(
      key,
      newer,
      generatorId: 'varied',
      generatorVersion: 1,
      regenerable: true,
      playerModified: false,
      finalized: true,
    );
    await first.flush();
    await first.close();
    await first.close();

    final log = File(p.join(root.path, 'region', 'r.0.0.1.ayur'));
    final intact = await log.readAsBytes();
    await log.writeAsBytes(intact.sublist(0, intact.length - 5), flush: true);
    final second = RegionLogStorage(root);
    await second.open();
    addTearDown(second.close);
    final restored = await second.lookup(key);
    expect(restored.kind, ChunkLookupKind.hit);
    expect(restored.payload!.pack(), orderedEquals(older.pack()));
  });

  test('a bad header is left untouched and a short length does not hide the last good record', () async {
    final root = await Directory.systemTemp.createTemp('ayu-ayur-header-');
    addTearDown(() async {
      if (await root.exists()) await root.delete(recursive: true);
    });
    final badRoot = Directory(p.join(root.path, 'bad'));
    await badRoot.create();
    final bad = RegionLogStorage(badRoot);
    await bad.open();
    final file = File(p.join(badRoot.path, 'region', 'r.0.0.1.ayur'));
    final header = Uint8List.fromList([
      0x41, 0x59, 0x55, 0x52, 2, 0, 0, 0, // AYUR, version 2
      9, 9, 9, 9,
    ]);
    await file.writeAsBytes(header, flush: true);
    await expectLater(bad.lookup(key), throwsA(isA<RegionLogException>()));
    expect(await file.readAsBytes(), orderedEquals(header));
    await bad.close();
    await bad.close();

    final good = RegionLogStorage(Directory(p.join(root.path, 'good')));
    await good.open();
    final payload = _varied(3, 4, salt: 4);
    const kept = ChunkKey(worldId: ChunkKey.overworld, x: 3, z: 4);
    await good.store(
      kept,
      payload,
      generatorId: 'varied',
      generatorVersion: 1,
      regenerable: true,
      playerModified: false,
      finalized: true,
    );
    await good.flush();
    await good.close();
    final goodFile = File(p.join(root.path, 'good', 'region', 'r.0.0.1.ayur'));
    final prefix = await goodFile.length();
    final raf = await goodFile.open(mode: FileMode.append);
    await raf.writeFrom(const [0xFF, 0xFF, 0xFF, 0x7F, 0, 0, 0, 0]);
    await raf.close();
    final reopened = RegionLogStorage(Directory(p.join(root.path, 'good')));
    await reopened.open();
    addTearDown(reopened.close);
    final hit = await reopened.lookup(kept);
    expect(hit.kind, ChunkLookupKind.hit);
    expect(hit.payload!.pack(), orderedEquals(payload.pack()));
    expect(await goodFile.length(), prefix);
  });

  test('a checksum-valid player-modified body with a bad format stays corrupt', () async {
    final root = await Directory.systemTemp.createTemp('ayu-ayur-crc-');
    addTearDown(() async {
      if (await root.exists()) await root.delete(recursive: true);
    });
    final storage = RegionLogStorage(root);
    await storage.open();
    final payload = _varied(key.x, key.z, salt: 8);
    await storage.store(
      key,
      payload,
      generatorId: 'varied',
      generatorVersion: 1,
      regenerable: false,
      playerModified: true,
      finalized: true,
    );
    await storage.close();
    final file = File(p.join(root.path, 'region', 'r.0.0.1.ayur'));
    final bytes = await file.readAsBytes();
    final body = _lastBody(bytes);
    final packed = payload.pack();
    final formatAt = body.length - packed.length;
    expect(body[formatAt], 1);
    body[formatAt] = 9;
    _writeCrc(bytes, _lastFrame(bytes), Crc32.compute(body));
    await file.writeAsBytes(bytes, flush: true);
    final again = RegionLogStorage(root);
    await again.open();
    addTearDown(again.close);
    final lookup = await again.lookup(key);
    expect(lookup.kind, ChunkLookupKind.corrupt);
    expect(lookup.playerModified, isTrue);
    expect(lookup.raw, isNotNull);
  });

  test('rewritten coordinates do not alias the previous key', () async {
    final root = await Directory.systemTemp.createTemp('ayu-ayur-coord-');
    addTearDown(() async {
      if (await root.exists()) await root.delete(recursive: true);
    });
    final storage = RegionLogStorage(root);
    await storage.open();
    final payload = _varied(1, 2, salt: 3);
    await storage.store(
      key,
      payload,
      generatorId: 'varied',
      generatorVersion: 1,
      regenerable: true,
      playerModified: true,
      finalized: true,
    );
    await storage.flush();
    final file = File(p.join(root.path, 'region', 'r.0.0.1.ayur'));
    final bytes = await file.readAsBytes();
    final body = _lastBody(bytes);
    final view = ByteData.sublistView(body);
    view.setInt32(0, key.x + 9, Endian.little);
    _writeCrc(bytes, _lastFrame(bytes), Crc32.compute(body));
    await file.writeAsBytes(bytes, flush: true);
    final mismatched = await storage.lookup(key);
    expect(mismatched.kind, ChunkLookupKind.corrupt);
    expect(mismatched.playerModified, isTrue);
    await storage.close();

    final reopened = RegionLogStorage(root);
    await reopened.open();
    addTearDown(reopened.close);
    expect((await reopened.lookup(key)).kind, ChunkLookupKind.miss);
    final moved = await reopened.lookup(
      ChunkKey(worldId: ChunkKey.overworld, x: key.x + 9, z: key.z),
    );
    expect(moved.kind, ChunkLookupKind.hit);
    expect(moved.payload!.pack(), orderedEquals(payload.pack()));
  });
}

ChunkPayload _varied(int x, int z, {required int salt}) {
  final sections = Uint8List(ChunkPayload.sectionBytes(true) * 2);
  for (var i = 0; i < 4096; i++) {
    final value = (salt * 1009 + x * 131 + z * 17 + i) & 0xFFFF;
    sections[i * 2] = value & 0xFF;
    sections[i * 2 + 1] = (value >> 8) & 0xFF;
  }
  for (var i = 0; i < 2048; i++) {
    sections[8192 + i] = (x + i + salt) & 0xFF;
    sections[ChunkPayload.sectionBytes(true) + 8192 + i] = (z + i + salt) & 0xFF;
  }
  final biomes = Uint8List(ChunkPayload.biomeBytes);
  for (var i = 0; i < biomes.length; i++) {
    biomes[i] = (x + z + i + salt) & 0xFF;
  }
  return ChunkPayload(
    primaryBitmask: 0x0003,
    skylight: true,
    biomes: biomes,
    sections: sections,
  );
}

int _lastFrame(Uint8List bytes) {
  var offset = 8;
  var last = 8;
  while (offset + 8 <= bytes.length) {
    final length = _le(bytes, offset);
    if (length <= 0 || offset + 8 + length > bytes.length) break;
    last = offset;
    offset += 8 + length;
  }
  return last;
}

Uint8List _lastBody(Uint8List bytes) {
  final offset = _lastFrame(bytes);
  final length = _le(bytes, offset);
  return Uint8List.sublistView(bytes, offset + 8, offset + 8 + length);
}

int _le(Uint8List bytes, int offset) =>
    bytes[offset] |
    (bytes[offset + 1] << 8) |
    (bytes[offset + 2] << 16) |
    (bytes[offset + 3] << 24);

void _writeCrc(Uint8List bytes, int frame, int crc) {
  bytes[frame + 4] = crc & 0xFF;
  bytes[frame + 5] = (crc >> 8) & 0xFF;
  bytes[frame + 6] = (crc >> 16) & 0xFF;
  bytes[frame + 7] = (crc >> 24) & 0xFF;
}
